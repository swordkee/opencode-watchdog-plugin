# =============================================================
# meta_watchdog.ps1 - watchdog for the watchdog (classic WDT-of-WDT).
#
# The V2 plugin runs inside the opencode server. If the plugin fails to load
# or the server hangs, nothing notices. This external process lives OUTSIDE
# that failure domain: every N minutes it checks the plugin's heartbeat
# (last "sweep done" line in plugin.log) and, when stale, posts a warning
# into the freshest top-level session through the HTTP API.
#
# Usage:
#   meta_watchdog.ps1 -Once                 single check
#   meta_watchdog.ps1 -Install [-IntervalMinutes 15]
#   meta_watchdog.ps1 -Uninstall
# Silent execution: install writes meta_run.vbs (window style 0) + schtasks.
# Log: ~/.local/state/opencode/watchdog/meta.log
# =============================================================
param(
  [switch]$Install,
  [switch]$Uninstall,
  [switch]$Once,
  [int]$StaleMinutes = 20,
  [int]$IntervalMinutes = 15,
  [string]$BaseUrl = "http://127.0.0.1:49374"
)

$ErrorActionPreference = "Stop"
$stateDir = Join-Path $env:USERPROFILE ".local\state\opencode\watchdog"
$pluginLog = Join-Path $stateDir "plugin.log"
$metaLog = Join-Path $stateDir "meta.log"
$taskName = "opencode-watchdog-meta"
$curl = "C:\windows\system32\curl.exe"

if (-not (Test-Path $stateDir)) { New-Item -ItemType Directory -Path $stateDir -Force | Out-Null }

function Log([string]$level, [string]$msg) {
  $line = ("{0} [{1}] {2}" -f (Get-Date -Format "yyyy-MM-dd HH:mm:ss"), $level, $msg)
  Add-Content -Path $metaLog -Value $line -Encoding UTF8
  Write-Host $line
}

if ($Install -or $Uninstall) {
  if ($Uninstall) {
    schtasks /End /TN $taskName 2>$null | Out-Null
    schtasks /Delete /TN $taskName /F | Out-Null
    Log "INFO" ("task '{0}' deleted" -f $taskName)
    exit 0
  }
  $self = $PSCommandPath
  $vbsPath = Join-Path (Split-Path -Parent $self) "meta_run.vbs"
  $vbs = "' meta_run.vbs - silent launcher (no console window). Regenerated by -Install." + [Environment]::NewLine +
         "CreateObject(""WScript.Shell"").Run ""powershell.exe -NoProfile -ExecutionPolicy Bypass -File """"{0}"""" -Once"", 0, False" -f $self
  [IO.File]::WriteAllText($vbsPath, $vbs, (New-Object Text.ASCIIEncoding))
  schtasks /Create /TN $taskName /TR ("wscript.exe " + $vbsPath) /SC MINUTE /MO $IntervalMinutes /F | Out-Null
  if ($LASTEXITCODE -ne 0) { Log "ERROR" ("schtasks failed rc={0}" -f $LASTEXITCODE); exit 1 }
  Log "INFO" ("task '{0}' installed: every {1} min via VBS (silent)" -f $taskName, $IntervalMinutes)
  exit 0
}

# --- auth + helpers ---------------------------------------------------------
$serviceJson = Join-Path $env:USERPROFILE ".local\state\opencode\service.json"
if (-not (Test-Path $serviceJson)) { Log "ERROR" "service.json not found"; exit 1 }
$svc = Get-Content $serviceJson -Raw | ConvertFrom-Json
$auth = "Basic " + [Convert]::ToBase64String([Text.Encoding]::ASCII.GetBytes("opencode:" + $svc.password))

function Get-Json([string]$url) {
  $tmp = [System.IO.Path]::GetTempFileName()
  & $curl -s -m 20 -H "Authorization: $auth" $url -o $tmp
  $code = $LASTEXITCODE
  if ($code -ne 0) {
    Remove-Item $tmp -Force -ErrorAction SilentlyContinue
    throw ("curl rc={0}" -f $code)
  }
  $text = [IO.File]::ReadAllText($tmp, [Text.Encoding]::UTF8)
  Remove-Item $tmp -Force -ErrorAction SilentlyContinue
  return ($text | ConvertFrom-Json)
}

# --- heartbeat check --------------------------------------------------------
# First: is the opencode server itself up? If it is not (op closed), the
# stale heartbeat means "op is down", NOT "plugin broken" — stay silent.
$serverBack = $false
try {
  $null = Get-Json ($BaseUrl + "/api/info")
  $serverBack = $true
} catch {
  # throttle the "server down" note to once per 2h
  $lastNote = $null
  if (Test-Path $metaLog) {
    foreach ($l in (Get-Content $metaLog -Tail 50 -ErrorAction SilentlyContinue)) {
      if ($l -match "server down") {
        try { $lastNote = [DateTime]::Parse($l.Substring(0, [Math]::Min(19, $l.Length))) } catch {}
      }
    }
  }
  if (-not $lastNote -or ((Get-Date) - $lastNote).TotalMinutes -ge 120) {
    Log "INFO" "server down (op closed?) - skip"
  }
  exit 0
}

$stale = $true
$detail = "plugin.log missing"
if (Test-Path $pluginLog) {
  $lines = Get-Content $pluginLog -Tail 400 -ErrorAction SilentlyContinue
  $last = $null
  foreach ($l in $lines) {
    if ($l -match "sweep done") {
      $ts = ($l -split " ")[0]
      try { $last = [DateTimeOffset]::Parse($ts) } catch {}
    }
  }
  if ($null -ne $last) {
    $ageMin = [Math]::Round((([DateTimeOffset]::UtcNow) - $last).TotalMinutes, 1)
    if ($ageMin -le $StaleMinutes) {
      $stale = $false
    } else {
      $detail = ("last sweep {0} min ago ({1})" -f $ageMin, $last.ToString("HH:mm:ss"))
    }
  } else {
    $detail = "no 'sweep done' line in plugin.log"
  }
}

if (-not $stale) {
  # healthy: stay silent (only anomalies are logged)
  exit 0
}

Log "WARN" ("primary watchdog heartbeat stale: {0}" -f $detail)

# --- throttle: at most one alert per 2h per fault (no 15-min spam) ----------
$throttleMin = 120
if (Test-Path $metaLog) {
  $lastAlert = $null
  foreach ($l in (Get-Content $metaLog -Tail 200 -ErrorAction SilentlyContinue)) {
    if ($l -match "alert posted") {
      $ts = $l.Substring(0, [Math]::Min(19, $l.Length))
      try { $lastAlert = [DateTime]::Parse($ts) } catch {}
    }
  }
  if ($lastAlert) {
    $sinceMin = ((Get-Date) - $lastAlert).TotalMinutes
    if ($sinceMin -lt $throttleMin) {
      Log "INFO" ("alert throttled: last alert {0} min ago (< {1} min)" -f [Math]::Round($sinceMin, 0), $throttleMin)
      exit 0
    }
  }
}

# --- alert: post into the freshest top-level session (independent channel) --
try {
  $active = Get-Json ($BaseUrl + "/api/session/active")
  $map = $active
  if ($active.data) { $map = $active.data }
  $activeIds = @()
  foreach ($p in $map.PSObject.Properties) { $activeIds += $p.Name }

  $all = Get-Json ($BaseUrl + "/api/session?limit=1000")
  $now = [DateTimeOffset]::UtcNow
  $target = $null
  $best = [double]::MaxValue
  foreach ($s in @($all.data)) {
    if ($null -eq $s -or -not $s.id) { continue }
    if ($s.parentID) { continue }                     # top-level only
    if ($activeIds -notcontains $s.id) { continue }   # must be live
    $u = if ($s.time -and $s.time.updated) { [int64]$s.time.updated } else { 0 }
    if ($u -le 0) { continue }
    $idle = (($now.ToUnixTimeMilliseconds() - $u) / 60000.0)
    if ($idle -lt $best) { $best = $idle; $target = $s.id }
  }

  if ($null -eq $target) {
    Log "WARN" "no live top-level session to alert"
    exit 0
  }

  $text = "[meta-watchdog] 主看门狗心跳异常：{0}。可能存在插件加载失败或 server 异常。请检查 ~/.local/state/opencode/watchdog/plugin.log（保存插件文件即热重载）。" -f $detail
  $body = @{ text = $text; delivery = "queue"; resume = $false } | ConvertTo-Json -Compress
  $bodyFile = [System.IO.Path]::GetTempFileName()
  $outFile = [System.IO.Path]::GetTempFileName()
  [IO.File]::WriteAllText($bodyFile, $body, (New-Object Text.UTF8Encoding($false)))
  $bodyRef = "@" + $bodyFile.Replace("\", "/")
  & $curl -s -m 20 -X POST -H "Authorization: $auth" -H "Content-Type: application/json" --data-binary $bodyRef ("{0}/api/session/{1}/prompt" -f $BaseUrl, $target) -o $outFile
  $code = $LASTEXITCODE
  Remove-Item $bodyFile -Force -ErrorAction SilentlyContinue
  Remove-Item $outFile -Force -ErrorAction SilentlyContinue
  Log "INFO" ("alert posted to {0} rc={1}" -f $target, $code)
} catch {
  Log "ERROR" ("alert failed: {0}" -f $_.Exception.Message)
}