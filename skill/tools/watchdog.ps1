# =============================================================
# watchdog.ps1 - opencode session watchdog (superagent-ops skill)
#
# Detects "fake running" sessions: listed in /api/session/active
# but /api/session time.updated has stalled. Read-only by default.
#
# Usage:
#   watchdog.ps1                          report only
#   watchdog.ps1 -Interrupt               interrupt stale sessions
#   watchdog.ps1 -Interrupt -ResumeFile C:\path\resume.txt
#                                         interrupt, then relaunch each with
#                                         "opencode run -s <id> --continue"
#                                         using UTF-8 instruction file
#   watchdog.ps1 -Report                  per-family progress report: each
#                                         top-level (main) session gets ONLY
#                                         its own family summary (steer if
#                                         the root is live, else queue);
#                                         never into worker subagents
#   watchdog.ps1 -Install [-IntervalMinutes 5] [-StaleMinutes 45]
#                                         register silent scheduled task
#                                         (wscript VBS launcher, no window)
#   watchdog.ps1 -Enable                  re-enable auto-disabled task
#   watchdog.ps1 -Uninstall               remove scheduled task
#   watchdog.ps1 -Status                  show last scan + log tail
#
# Auto-off: when the active map is empty (all tasks delivered), the
# scheduled task disables itself and queues a farewell note.
#
# Stale criterion: session in active map AND idle >= StaleMinutes.
# outcome=succeeded is NOT trusted (proven unreliable on this machine).
# Log/state: %USERPROFILE%\.local\state\opencode\watchdog\
# ASCII-only source (PS5.1 reads non-BOM UTF-8 as ANSI); Chinese appears
# only as data pulled from the API, never as source literals.
# =============================================================
param(
  [int]$StaleMinutes = 45,
  [switch]$Interrupt,
  [string]$ResumeFile,
  [switch]$Report,
  [int]$ReportMaxIdle = 10,
  [switch]$Install,
  [switch]$Uninstall,
  [switch]$Enable,
  [switch]$Status,
  [int]$IntervalMinutes = 5,
  [string]$BaseUrl = "http://127.0.0.1:49374"
)

$ErrorActionPreference = "Stop"
$stateDir = Join-Path $env:USERPROFILE ".local\state\opencode\watchdog"
$logFile  = Join-Path $stateDir "watchdog.log"
$scanFile = Join-Path $stateDir "last-scan.json"
$curl     = "C:\windows\system32\curl.exe"
$taskName = "opencode-watchdog"

if (-not (Test-Path $stateDir)) { New-Item -ItemType Directory -Path $stateDir -Force | Out-Null }

function Log([string]$level, [string]$msg) {
  $line = ("{0} [{1}] {2}" -f (Get-Date -Format "yyyy-MM-dd HH:mm:ss"), $level, $msg)
  Add-Content -Path $logFile -Value $line -Encoding UTF8
  Write-Host $line
}

function Task-Exists {
  schtasks /Query /TN $taskName > $null 2>&1
  return ($LASTEXITCODE -eq 0)
}

# --- scheduled task management -------------------------------------------
if ($Install -or $Uninstall) {
  if ($Uninstall) {
    schtasks /End /TN $taskName 2>$null | Out-Null
    schtasks /Delete /TN $taskName /F | Out-Null
    Log "INFO" ("scheduled task '{0}' deleted" -f $taskName)
    exit 0
  }
  $self = $PSCommandPath
  # silent launcher: VBS runs powershell with window style 0 (no flash)
  $argStr = "-Interrupt -Report -StaleMinutes {0}" -f $StaleMinutes
  if ($ResumeFile) { $argStr = "{0} -ResumeFile {1}" -f $argStr, $ResumeFile }
  $vbsPath = Join-Path (Split-Path -Parent $self) "watchdog_run.vbs"
  $vbs = "' watchdog_run.vbs - silent launcher for watchdog.ps1 (no console window)." + [Environment]::NewLine +
         "' Regenerated by 'watchdog.ps1 -Install'; edit params there, not here." + [Environment]::NewLine +
         "CreateObject(""WScript.Shell"").Run ""powershell.exe -NoProfile -ExecutionPolicy Bypass -File """"{0}"""" {1}"", 0, False" -f $self, $argStr
  [IO.File]::WriteAllText($vbsPath, $vbs, (New-Object Text.ASCIIEncoding))
  schtasks /Create /TN $taskName /TR ("wscript.exe " + $vbsPath) /SC MINUTE /MO $IntervalMinutes /F | Out-Null
  if ($LASTEXITCODE -ne 0) { Log "ERROR" ("schtasks failed rc={0}" -f $LASTEXITCODE); exit 1 }
  Log "INFO" ("scheduled task '{0}' installed: every {1} min via VBS (silent), -Interrupt -Report -StaleMinutes {2}{3}" -f $taskName, $IntervalMinutes, $StaleMinutes, $(if ($ResumeFile) { " (auto-resume ON)" } else { "" }))
  exit 0
}

if ($Enable) {
  if (Task-Exists) {
    schtasks /Change /TN $taskName /ENABLE | Out-Null
    Log "INFO" ("scheduled task '{0}' re-enabled" -f $taskName)
  } else {
    Log "ERROR" ("task '{0}' not found; run -Install first" -f $taskName)
    exit 1
  }
  exit 0
}

if ($Status) {
  Write-Host "=== last scan ==="
  if (Test-Path $scanFile) { Get-Content $scanFile -Raw | Write-Host } else { Write-Host "(no scan yet)" }
  Write-Host "=== log tail ==="
  if (Test-Path $logFile) { Get-Content $logFile -Tail 30 | Write-Host }
  exit 0
}

# --- helpers --------------------------------------------------------------
function Get-Json([string]$url) {
  $tmp = [System.IO.Path]::GetTempFileName()
  & $curl -s -m 30 -H "Authorization: $auth" $url -o $tmp
  $code = $LASTEXITCODE   # take rc BEFORE any pipeline (house rule)
  if ($code -ne 0) {
    Remove-Item $tmp -Force -ErrorAction SilentlyContinue
    throw ("curl rc={0} for {1}" -f $code, $url)
  }
  $text = [IO.File]::ReadAllText($tmp, [Text.Encoding]::UTF8)
  Remove-Item $tmp -Force -ErrorAction SilentlyContinue
  return ($text | ConvertFrom-Json)
}

function Post-Report([string]$sessionId, [string]$delivery, [string]$text) {
  $bodyObj = @{ text = $text; delivery = $delivery; resume = $false }
  $json = $bodyObj | ConvertTo-Json -Compress
  $bodyFile = [System.IO.Path]::GetTempFileName()
  $outFile  = [System.IO.Path]::GetTempFileName()
  # UTF-8 no BOM (house rule); forward slashes after @ (backslash path = CURLE_READ_ERROR, documented trap)
  [IO.File]::WriteAllText($bodyFile, $json, (New-Object Text.UTF8Encoding($false)))
  $bodyRef = "@" + $bodyFile.Replace("\", "/")
  & $curl -s -m 30 -X POST -H "Authorization: $auth" -H "Content-Type: application/json" --data-binary $bodyRef ("{0}/api/session/{1}/prompt" -f $BaseUrl, $sessionId) -o $outFile
  $code = $LASTEXITCODE
  $respText = ""
  if (Test-Path $outFile) { $respText = [IO.File]::ReadAllText($outFile, [Text.Encoding]::UTF8); Remove-Item $outFile -Force -ErrorAction SilentlyContinue }
  Remove-Item $bodyFile -Force -ErrorAction SilentlyContinue
  Log "INFO" ("report -> {0} via {1} rc={2} resp={3}" -f $sessionId, $delivery, $code, $respText)
}

# --- auth ------------------------------------------------------------------
$serviceJson = Join-Path $env:USERPROFILE ".local\state\opencode\service.json"
if (-not (Test-Path $serviceJson)) { Log "ERROR" "service.json not found"; exit 1 }
$svc = Get-Content $serviceJson -Raw | ConvertFrom-Json
$password = $svc.password
if ([string]::IsNullOrEmpty($password)) { Log "ERROR" "service.json password empty"; exit 1 }
$auth = "Basic " + [Convert]::ToBase64String([Text.Encoding]::ASCII.GetBytes("opencode:" + $password))

# --- fetch active map + full session list ----------------------------------
try { $active = Get-Json ($BaseUrl + "/api/session/active") }
catch { Log "ERROR" ("fetch active failed: {0}" -f $_.Exception.Message); exit 1 }

$activeIds = @()
if ($active) {
  $map = $active
  if ($active.data) { $map = $active.data }   # response wraps map in {"data":{...}}
  foreach ($p in $map.PSObject.Properties) { $activeIds += $p.Name }
}

try { $all = Get-Json ($BaseUrl + "/api/session?limit=1000") }
catch { Log "ERROR" ("fetch sessions failed: {0}" -f $_.Exception.Message); exit 1 }

$allList = @()
if ($all.data) { $allList = @($all.data) }

$now = [DateTimeOffset]::UtcNow
$results = @()
$candidates = @()
$runningCount = 0

foreach ($s in $allList) {
  if ($null -eq $s -or -not $s.id) { continue }
  if ($activeIds -notcontains $s.id) { continue }
  $runningCount++

  $title = ""; $dir = ""; $outcome = ""; $parent = ""
  if ($s.title) { $title = $s.title }
  if ($s.location -and $s.location.directory) { $dir = $s.location.directory }
  if ($s.outcome) { $outcome = $s.outcome }
  if ($s.parentID) { $parent = $s.parentID }   # subagent sessions carry a parentID; main sessions do not

  $idleMin = -1; $updText = "unknown"
  if ($s.time -and $s.time.updated) {
    try {
      $upd = [DateTimeOffset]::FromUnixTimeMilliseconds([int64]$s.time.updated)
      $idleMin = [int][Math]::Round(($now - $upd).TotalMinutes, 0)
      $updText = $upd.ToLocalTime().ToString("yyyy-MM-dd HH:mm:ss")
    } catch { $updText = "parse-error" }
  }

  $stale = ($idleMin -ge $StaleMinutes)
  if ($stale) { $candidates += $s.id }

  $results += [pscustomobject]@{
    sessionID = $s.id; parentID = $parent; title = $title; directory = $dir; outcome = $outcome
    lastUpdated = $updText; idleMinutes = $idleMin; stale = $stale
  }
  Log "INFO" ("running {0} title='{1}' dir='{2}' outcome={3} idle={4}min stale={5}" -f $s.id, $title, $dir, $outcome, $idleMin, $stale)
}

$scan = [pscustomobject]@{
  scannedAt   = $now.ToLocalTime().ToString("yyyy-MM-dd HH:mm:ss")
  baseUrl     = $BaseUrl
  staleAfter  = $StaleMinutes
  runningCount = $runningCount
  candidates  = $candidates
  results     = $results
}
$scan | ConvertTo-Json -Depth 4 | Set-Content -Path $scanFile -Encoding UTF8

# --- interrupt stale sessions ----------------------------------------------
$interrupted = @()
if ($Interrupt -and $candidates.Count -gt 0) {
  foreach ($id in $candidates) {
    try {
      $tmp = [System.IO.Path]::GetTempFileName()
      & $curl -s -m 30 -X POST -H "Authorization: $auth" -H "Content-Type: application/json" -d "{}" ($BaseUrl + "/api/session/" + $id + "/interrupt") -o $tmp
      $code = $LASTEXITCODE
      $respText = ""
      if (Test-Path $tmp) { $respText = [IO.File]::ReadAllText($tmp, [Text.Encoding]::UTF8); Remove-Item $tmp -Force -ErrorAction SilentlyContinue }
      Log "INFO" ("interrupt {0} rc={1} resp={2}" -f $id, $code, $respText)
      if ($code -eq 0) { $interrupted += $id }
    } catch {
      Log "ERROR" ("interrupt {0} failed: {1}" -f $id, $_.Exception.Message)
    }
  }
  Start-Sleep -Seconds 3
  try {
    $active2 = Get-Json ($BaseUrl + "/api/session/active")
    $stillIds = @()
    if ($active2) {
      $map2 = $active2
      if ($active2.data) { $map2 = $active2.data }
      foreach ($p in $map2.PSObject.Properties) { $stillIds += $p.Name }
    }
    foreach ($id in $interrupted) {
      if ($stillIds -contains $id) {
        Log "WARN" ("interrupt NOT confirmed for {0} (still active; stuck session, will retry next run)" -f $id)
      } else {
        Log "INFO" ("interrupt confirmed for {0}" -f $id)
      }
    }
  } catch {
    Log "WARN" ("post-interrupt verify failed: {0}" -f $_.Exception.Message)
  }
}

# --- auto-off: nothing running = all tasks delivered ------------------------
$autoOff = $false
if ($runningCount -eq 0 -and (Task-Exists)) {
  schtasks /Change /TN $taskName /DISABLE | Out-Null
  $autoOff = $true
  Log "WARN" ("auto-DISABLED task '{0}': active map is empty (all subtask results delivered). Re-enable: watchdog.ps1 -Enable" -f $taskName)
}

# --- per-family report -------------------------------------------------------
# Multiple main sessions may run in parallel, each with its own worker fleet.
# Group active sessions into families by walking parentID chains up to the
# top-level root; each root gets ONLY its own family summary. Delivery:
# steer if the root itself is live (idle < ReportMaxIdle), else queue so it
# lands next turn. Never post into a worker subagent.
if ($Report) {
  $allById = @{}
  foreach ($s in $allList) { if ($s -and $s.id) { $allById[$s.id] = $s } }

  $famMembers = @{}; $famOf = @{}
  foreach ($r in $results) {
    $rid = $null
    if (-not $r.parentID) { $rid = $r.sessionID }
    else {
      $cur = $r.parentID; $depth = 0
      while ($cur -and $depth -lt 10) {
        if ($allById.ContainsKey($cur) -and $allById[$cur].parentID) { $cur = $allById[$cur].parentID; $depth++ }
        else { break }
      }
      $rid = $cur
    }
    if (-not $rid) { $rid = "(orphan)" }
    $famOf[$r.sessionID] = $rid
    if (-not $famMembers.ContainsKey($rid)) { $famMembers[$rid] = @() }
    $famMembers[$rid] = @($famMembers[$rid]) + $r
  }

  if ($autoOff) {
    $rootRecs = @($results | Where-Object { -not $_.parentID } | Sort-Object idleMinutes)
    if ($rootRecs.Count -gt 0) {
      Post-Report $rootRecs[0].sessionID "queue" ("[watchdog {0}] auto-disabled: no running sessions left (all subtask results delivered). Re-enable: watchdog.ps1 -Enable" -f (Get-Date -Format "HH:mm"))
    } else {
      Log "INFO" "auto-off notice skipped: no session to post to"
    }
  } else {
    $stamp = Get-Date -Format "HH:mm"
    foreach ($rootID in $famMembers.Keys) {
      $members = @($famMembers[$rootID])
      if ($members.Count -lt 2) { continue }   # solo main session: nothing to report
      if ($rootID -eq "(orphan)" -or -not $allById.ContainsKey($rootID)) {
        Log "INFO" ("report skipped for family root={0}: root session unknown" -f $rootID)
        continue
      }
      $rootAll = $allById[$rootID]
      $rootTitle = ""
      if ($rootAll.title) { $rootTitle = $rootAll.title }
      if ($rootTitle.Length -gt 24) { $rootTitle = $rootTitle.Substring(0, 24) + "..." }
      $list = ($members | ForEach-Object {
        $t = $_.title
        if ($t.Length -gt 24) { $t = $t.Substring(0, 24) + "..." }
        "{0}(idle {1}m)" -f $t, $_.idleMinutes
      }) -join "; "
      $staleN = @($members | Where-Object { $_.stale }).Count
      $intN = @($interrupted | Where-Object { $famOf[$_] -eq $rootID }).Count
      $text = "[watchdog {0} | family '{1}'] members {2}: {3}. stale: {4}; interrupted now: {5}. (auto-report, no reply needed, keep working)" -f $stamp, $rootTitle, $members.Count, $list, $staleN, $intN
      $delivery = "queue"
      $rootLive = @($members | Where-Object { $_.sessionID -eq $rootID })
      if ($rootLive.Count -gt 0 -and $rootLive[0].idleMinutes -ge 0 -and $rootLive[0].idleMinutes -lt $ReportMaxIdle) { $delivery = "steer" }
      Post-Report $rootID $delivery $text
    }
  }
}

# --- optional auto-resume ----------------------------------------------------
if ($ResumeFile -and $interrupted.Count -gt 0) {
  if (-not (Test-Path $ResumeFile)) { Log "ERROR" ("ResumeFile not found: {0}" -f $ResumeFile); exit 1 }

  $here = Split-Path -Parent $PSCommandPath
  $jsFile = Join-Path $here "resume_runner.js"
  if (-not (Test-Path $jsFile)) { Log "ERROR" "resume_runner.js not found next to watchdog.ps1"; exit 1 }

  $nodeExe = $null
  try { $nodeExe = (Get-Command node.exe -ErrorAction Stop).Source } catch {}
  if (-not $nodeExe) { Log "ERROR" "node.exe not on PATH"; exit 1 }

  $ocExe = "D:\Dev\Scoop\apps\nodejs-lts\current\bin\node_modules\@opencode\cli\bin\opencode.exe"
  if (-not (Test-Path $ocExe)) {
    try { $cand = (Get-Command opencode -ErrorAction Stop).Source } catch { $cand = $null }
    if ($cand -and $cand.EndsWith(".exe") -and (Test-Path $cand)) { $ocExe = $cand }
    else { Log "ERROR" "opencode.exe not found"; exit 1 }
  }

  foreach ($id in $interrupted) {
    $rlog = Join-Path $stateDir ("resume-{0}.log" -f $id)
    $args = '"{0}" "{1}" "{2}" "{3}" "{4}"' -f $jsFile, $id, $ResumeFile, $rlog, $ocExe
    Start-Process -FilePath $nodeExe -ArgumentList $args -WindowStyle Hidden
    Log "INFO" ("resume launched for {0} (node detached, log: {1})" -f $id, $rlog)
  }
}

if (-not $Report) {
  Log "INFO" ("scan done: {0} running, {1} stale, {2} interrupted{3}" -f $runningCount, $candidates.Count, $interrupted.Count, $(if ($autoOff) { ", task auto-disabled" } else { "" }))
}
